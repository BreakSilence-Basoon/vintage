import { test } from 'node:test';
import assert from 'node:assert/strict';
import { DatabaseSync } from 'node:sqlite';
import { mkdtempSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join, resolve } from 'node:path';
import { once } from 'node:events';
import { exportJWK, generateKeyPair, SignJWT } from 'jose';
import { migrateWithBackup } from '@vintage/timetable-store/operations';
import { initializeNewDatabase } from '../src/init-db.mjs';
import { prepareService } from '../src/main.mjs';

test('opt-in write HTTP enforces scope, current admin role, tenant and audit', async () => {
  const prefix = join(tmpdir(), 'vintage-admin-http-');
  const temp = mkdtempSync(prefix);
  let writer, service;
  try {
    const database = join(temp, 'fixture.sqlite');
    const issuer = 'https://identity.example.invalid';
    initializeNewDatabase(database, { issuer, subject: 'example-admin', businessId: 'shop-a', staffId: 'admin-a' });
    await migrateWithBackup(database, join(temp, 'v1-backup.sqlite'));
    await migrateWithBackup(database, join(temp, 'v2-backup.sqlite'));
    await migrateWithBackup(database, join(temp, 'v3-backup.sqlite'));
    await migrateWithBackup(database, join(temp, 'v4-backup.sqlite'));
    await migrateWithBackup(database, join(temp, 'v5-backup.sqlite'));
    await migrateWithBackup(database, join(temp, 'v6-backup.sqlite'));
    await migrateWithBackup(database, join(temp, 'v7-backup.sqlite'));
    await migrateWithBackup(database, join(temp, 'v8-backup.sqlite'));
    await migrateWithBackup(database, join(temp, 'v9-backup.sqlite'));
    writer = new DatabaseSync(database);
    writer.prepare('INSERT INTO businesses (id) VALUES (?)').run('shop-b');
    writer.prepare('INSERT INTO staff (business_id,id) VALUES (?,?)').run('shop-b', 'foreign-staff');
    writer.prepare('INSERT INTO staff (business_id,id) VALUES (?,?)').run('shop-b', 'foreign-admin');
    writer.prepare('INSERT INTO memberships (issuer,subject,business_id,staff_id,role,active) VALUES (?,?,?,?,?,1)')
      .run(issuer, 'example-foreign', 'shop-b', 'foreign-staff', 'VIEWER');
    writer.prepare('INSERT INTO memberships (issuer,subject,business_id,staff_id,role,active) VALUES (?,?,?,?,?,1)')
      .run(issuer, 'example-foreign-admin', 'shop-b', 'foreign-admin', 'ADMIN');
    const keys = await generateKeyPair('RS256', { extractable: true });
    const publicKey = { ...await exportJWK(keys.publicKey), kid: 'fixture-key', alg: 'RS256', use: 'sig' };
    const keyFile = join(temp, 'fixture-public-keys.json');
    writeFileSync(keyFile, JSON.stringify({ keys: [publicKey] }));
    const config = { VINTAGE_ISSUER: issuer, VINTAGE_AUDIENCE: 'example-api', VINTAGE_CLIENT_ID: 'example-client',
      VINTAGE_REQUIRED_SCOPE: 'timetable:access', VINTAGE_WRITE_SCOPE: 'timetable:write', VINTAGE_ENABLE_WRITES: 'true',
      VINTAGE_JWKS_FILE: keyFile, VINTAGE_DATABASE_FILE: database, VINTAGE_PORT: '3004' };
    assert.throws(() => prepareService({ ...config, VINTAGE_WRITE_SCOPE: 'timetable:access' }));
    assert.throws(() => prepareService({ ...config, VINTAGE_ENABLE_WRITES: 'yes' }));
    writer.exec('PRAGMA user_version = 2');
    assert.throws(() => prepareService(config), /Migration required/);
    writer.exec('PRAGMA user_version = 10');
    service = prepareService(config);
    service.server.listen(0, '127.0.0.1');
    await once(service.server, 'listening');
    const base = `http://127.0.0.1:${service.server.address().port}`;
    const signed = async (sub, scope) => new SignJWT({ iss: issuer, aud: 'example-api', sub, jti: 'example-token',
      client_id: 'example-client', scope }).setIssuedAt().setExpirationTime('5m')
      .setProtectedHeader({ alg: 'RS256', typ: 'at+jwt', kid: 'fixture-key' }).sign(keys.privateKey);
    const admin = await signed('example-admin', 'timetable:access timetable:write');
    const readOnlyAdmin = await signed('example-admin', 'timetable:access');
    const viewer = await signed('example-viewer', 'timetable:access timetable:write');
    const foreignViewer = await signed('example-foreign', 'timetable:access');
    const foreignAdmin = await signed('example-foreign-admin', 'timetable:access timetable:write');
    const post = (path, bearer, body, extra = {}) => fetch(base + path, { method: 'POST',
      headers: { authorization: `Bearer ${bearer}`, 'content-type': 'application/json; charset=utf-8', ...extra }, body: JSON.stringify(body) });
    assert.equal((await post('/v1/admin/viewers', readOnlyAdmin, { staffId: 'staff-a', subject: 'example-viewer' })).status, 401);
    const created = await post('/v1/admin/viewers', admin, { staffId: 'staff-a', subject: 'example-viewer' });
    assert.equal(created.status, 200);
    const location = { locationId: 'location-a', label: 'Example location' };
    const shift = { shiftId: 'shift-a', staffId: 'staff-a', locationId: 'location-a', startsAt: '2026-01-01T09:00:00.000Z', endsAt: '2026-01-01T17:00:00.000Z', graceMinutes: 0 };
    assert.equal((await post('/v1/admin/locations', readOnlyAdmin, location)).status, 401);
    assert.equal((await post('/v1/admin/locations', viewer, location)).status, 403);
    assert.equal((await post('/v1/admin/locations', admin, location)).status, 200);
    assert.equal((await post('/v1/admin/shifts', viewer, shift)).status, 403);
    assert.equal((await post('/v1/admin/shifts', admin, { ...shift, staffId: 'foreign-staff' })).status, 400);
    assert.equal((await post('/v1/admin/shifts', admin, shift)).status, 200);
    assert.equal((await post('/v1/admin/shifts', admin, { ...shift, shiftId: 'shift-b' })).status, 409);
    assert.equal((await post('/v1/admin/shifts', admin, { ...shift, shiftId: 'shift-b', startsAt: shift.endsAt, endsAt: '2026-01-01T18:00:00.000Z' })).status, 200);
    const params = new URLSearchParams({ from: '2026-01-01T00:00:00.000Z', to: '2026-01-02T00:00:00.000Z', limit: '1' });
    const ownUrl = `${base}/v1/me/shifts?${params}`;
    const authHeader = { authorization: `Bearer ${viewer}` };
    const firstShift = await (await fetch(ownUrl, { headers: authHeader })).json();
    assert.deepEqual(firstShift.shifts.map((item) => item.id), ['shift-b']);
    params.set('cursor', firstShift.nextCursor);
    const next = await (await fetch(`${base}/v1/me/shifts?${params}`, { headers: authHeader })).json();
    assert.deepEqual(next.shifts.map((item) => item.id), ['shift-a']);
    assert.equal(next.nextCursor, null);
    assert.deepEqual((await (await fetch(ownUrl, { headers: { authorization: `Bearer ${admin}` } })).json()).shifts, []);
    assert.deepEqual((await (await fetch(ownUrl, { headers: { authorization: `Bearer ${foreignViewer}` } })).json()).shifts, []);
    assert.equal((await fetch(`${base}/v1/me/shifts?from=invalid`, { headers: authHeader })).status, 400);
    assert.equal((await fetch(ownUrl)).status, 401);
    assert.equal((await post('/v1/admin/shifts', admin, { ...shift, shiftId: 'shift-before', startsAt: '2025-12-31T23:00:00.000Z', endsAt: shift.startsAt })).status, 200);
    const boundary = new URLSearchParams({ from: '2026-01-01T08:30:00.000Z', to: shift.startsAt });
    assert.deepEqual((await (await fetch(`${base}/v1/me/shifts?${boundary}`, { headers: authHeader })).json()).shifts.map((item) => item.id), ['shift-before']);
    const adminShiftUrl = `${base}/v1/admin/shifts/shift-a`;
    assert.equal((await fetch(adminShiftUrl, { headers: authHeader })).status, 404);
    const adminHeaders = { authorization: `Bearer ${admin}` };
    assert.equal(service.db.prepare('PRAGMA busy_timeout').get().timeout, 0);
    const lockedLocation = { locationId: 'locked-location', label: 'Example locked location' };
    writer.exec('BEGIN IMMEDIATE');
    try {
      const blocked = await post('/v1/admin/locations', admin, lockedLocation);
      assert.equal(blocked.status, 503);
      assert.deepEqual(await blocked.json(), { error: 'unavailable' });
      assert.equal(writer.prepare('SELECT COUNT(*) AS n FROM schedule_locations WHERE id=?').get('locked-location').n, 0);
    } finally { writer.exec('ROLLBACK'); }
    assert.equal((await post('/v1/admin/locations', admin, lockedLocation)).status, 200);
    const staffUrl = `${base}/v1/admin/staff?limit=1`;
    assert.equal((await fetch(staffUrl, { headers: authHeader })).status, 404);
    assert.equal((await fetch(staffUrl, { headers: { authorization: `Bearer ${readOnlyAdmin}` } })).status, 401);
    const staffFirst = await (await fetch(staffUrl, { headers: adminHeaders })).json();
    assert.deepEqual(staffFirst.staff, [{ id: 'admin-a', role: 'ADMIN', status: 'active' }]);
    const staffNext = await (await fetch(`${staffUrl}&cursor=${staffFirst.nextCursor}`, { headers: adminHeaders })).json();
    assert.deepEqual(staffNext.staff, [{ id: 'staff-a', role: 'VIEWER', status: 'active' }]);
    assert.equal(staffNext.nextCursor, null);
    const copy = { sourceShiftId: 'shift-a', sourceRevision: 1, shiftId: 'copied-shift', startsAt: '2026-01-02T09:00:00.000Z', endsAt: '2026-01-02T17:00:00.000Z' };
    assert.equal((await post('/v1/admin/shifts/copy', viewer, copy)).status, 403);
    assert.equal((await post('/v1/admin/shifts/copy', admin, { ...copy, sourceRevision: 2 })).status, 409);
    assert.deepEqual(await (await post('/v1/admin/shifts/copy', admin, copy)).json(), { ok: true, replayed: false });
    assert.deepEqual(await (await post('/v1/admin/shifts/copy', admin, copy)).json(), { ok: true, replayed: true });
    assert.equal((await post('/v1/admin/locations', foreignAdmin, { locationId: 'foreign-location', label: 'Other example location' })).status, 200);
    assert.equal((await post('/v1/admin/shifts', foreignAdmin, { ...shift, shiftId: 'foreign-shift', staffId: 'foreign-staff', locationId: 'foreign-location' })).status, 200);
    assert.equal((await post('/v1/admin/shifts/copy', foreignAdmin, { ...copy, shiftId: 'foreign-copy' })).status, 409);
    const adminParams = new URLSearchParams({ from: '2026-01-01T00:00:00.000Z', to: '2026-01-02T00:00:00.000Z', limit: '2', status: 'all' });
    const adminList = `${base}/v1/admin/shifts?${adminParams}`;
    assert.equal((await fetch(adminList, { headers: authHeader })).status, 404);
    assert.equal((await fetch(adminList, { headers: { authorization: `Bearer ${readOnlyAdmin}` } })).status, 401);
    const adminPage = await (await fetch(adminList, { headers: adminHeaders })).json();
    assert.deepEqual(adminPage.shifts.map((item) => item.id), ['shift-b', 'shift-a']);
    assert.ok(adminPage.shifts.every((item) => item.staffId === 'staff-a'));
    adminParams.set('cursor', adminPage.nextCursor);
    const adminNext = await (await fetch(`${base}/v1/admin/shifts?${adminParams}`, { headers: adminHeaders })).json();
    assert.deepEqual(adminNext.shifts.map((item) => item.id), ['shift-before']);
    assert.equal(adminNext.nextCursor, null);
    assert.deepEqual((await (await fetch(adminList, { headers: { authorization: `Bearer ${foreignAdmin}` } })).json()).shifts.map((item) => item.id), ['foreign-shift']);
    assert.equal((await fetch(`${adminList}&status=all`, { headers: adminHeaders })).status, 400);
    assert.equal((await (await fetch(adminShiftUrl, { headers: adminHeaders })).json()).revision, 1);
    const correction = { ...shift, endsAt: '2026-01-01T16:30:00.000Z', expectedRevision: 1, reason: 'Example correction' };
    assert.equal((await post('/v1/admin/shifts/update', viewer, correction)).status, 403);
    assert.equal((await post('/v1/admin/shifts/update', admin, correction)).status, 200);
    assert.equal((await post('/v1/admin/shifts/update', admin, correction)).status, 409);
    assert.equal((await post('/v1/admin/shifts/cancel', admin, { shiftId: 'shift-a', expectedRevision: 2, reason: 'Example cancellation' })).status, 200);
    const canceledWindow = new URLSearchParams({ from: '2026-01-01T10:00:00.000Z', to: '2026-01-01T16:00:00.000Z' });
    assert.deepEqual((await (await fetch(`${base}/v1/me/shifts?${canceledWindow}`, { headers: authHeader })).json()).shifts, []);
    const canceled = await (await fetch(adminShiftUrl, { headers: adminHeaders })).json();
    assert.equal(canceled.active, false);
    assert.equal(canceled.revision, 3);
    const canceledParams = new URLSearchParams({ from: '2026-01-01T00:00:00.000Z', to: '2026-01-02T00:00:00.000Z', status: 'canceled' });
    assert.deepEqual((await (await fetch(`${base}/v1/admin/shifts?${canceledParams}`, { headers: adminHeaders })).json()).shifts.map((item) => item.id), ['shift-a']);
    assert.equal((await post('/v1/admin/shifts/restore', admin, { shiftId: 'shift-a', expectedRevision: 3, reason: 'Example restore' })).status, 200);
    assert.deepEqual((await (await fetch(`${base}/v1/me/shifts?${canceledWindow}`, { headers: authHeader })).json()).shifts.map((item) => item.id), ['shift-a']);
    assert.equal(created.headers.get('cache-control'), 'no-store');
    assert.equal(created.headers.get('access-control-allow-origin'), null);
    const record = { staffId: 'staff-a', recordId: 'record-a', startsAt: '2026-01-01T09:00:00.000Z', endsAt: null };
    assert.equal((await post('/v1/admin/history', viewer, record, { 'x-role': 'ADMIN' })).status, 403);
    assert.equal((await post('/v1/admin/history', admin, { ...record, businessId: 'shop-b' })).status, 400);
    const foreign = await post('/v1/admin/history', admin, { ...record, staffId: 'foreign-staff' });
    assert.equal(foreign.status, 503);
    assert.deepEqual(await foreign.json(), { error: 'unavailable' });
    assert.equal((await post('/v1/admin/history', admin, record, { 'content-type': 'text/plain' })).status, 415);
    const first = await post('/v1/admin/history', admin, record);
    assert.equal(first.status, 200);
    assert.deepEqual(await first.json(), { ok: true, replayed: false });
    const replay = await post('/v1/admin/history', admin, record);
    assert.equal(replay.status, 200);
    assert.deepEqual(await replay.json(), { ok: true, replayed: true });
    assert.equal((await post('/v1/admin/history', admin, { ...record, startsAt: '2026-01-01T10:00:00.000Z' })).status, 409);
    assert.equal((await post('/v1/admin/history', admin, { ...record, recordId: 'record-b', startsAt: '2026-01-01T10:00:00.000Z' })).status, 409);
    assert.equal((await post('/v1/admin/history', admin, { ...record, recordId: 'record-c', endsAt: record.startsAt })).status, 400);
    const close = { recordId: 'record-a', endsAt: '2026-01-01T10:00:00.000Z' };
    assert.equal((await post('/v1/admin/history/close', viewer, close)).status, 403);
    assert.equal((await post('/v1/admin/history/close', admin, { ...close, endsAt: record.startsAt })).status, 409);
    const closed = await post('/v1/admin/history/close', admin, close);
    assert.deepEqual(await closed.json(), { ok: true, replayed: false });
    const repeatedClose = await post('/v1/admin/history/close', admin, close);
    assert.deepEqual(await repeatedClose.json(), { ok: true, replayed: true });
    assert.equal((await post('/v1/admin/history/close', admin, { ...close, endsAt: '2026-01-01T11:00:00.000Z' })).status, 409);
    const viewed = await fetch(base + '/v1/history/record-a', { headers: { authorization: `Bearer ${viewer}` } });
    assert.equal(viewed.status, 200);
    assert.equal((await viewed.json()).endsAt, close.endsAt);
    assert.equal((await post('/v1/admin/viewers/deactivate', admin, { staffId: 'staff-a' })).status, 200);
    assert.equal((await fetch(base + '/v1/history/record-a', { headers: { authorization: `Bearer ${viewer}` } })).status, 404);
    assert.equal((await fetch(ownUrl, { headers: authHeader })).status, 404);
    assert.deepEqual((await (await fetch(`${staffUrl}&cursor=admin-a`, { headers: adminHeaders })).json()).staff,
      [{ id: 'staff-a', role: 'VIEWER', status: 'inactive' }]);
    assert.equal((await post('/v1/admin/viewers/reactivate', viewer, { staffId: 'staff-a', reason: 'Example restoration' })).status, 403);
    assert.equal((await post('/v1/admin/viewers/reactivate', admin, { staffId: 'foreign-staff', reason: 'Example restoration' })).status, 409);
    writer.exec("CREATE TRIGGER reject_reactivation_audit BEFORE INSERT ON membership_reactivation_events BEGIN SELECT RAISE(ABORT, 'test failure'); END");
    assert.equal((await post('/v1/admin/viewers/reactivate', admin, { staffId: 'staff-a', reason: 'Example restoration' })).status, 503);
    assert.deepEqual({ ...writer.prepare('SELECT active,token_valid_after FROM memberships WHERE subject = ?').get('example-viewer') }, { active: 0, token_valid_after: 0 });
    writer.exec('DROP TRIGGER reject_reactivation_audit');
    assert.equal((await post('/v1/admin/viewers/reactivate', admin, { staffId: 'staff-a', reason: 'Example restoration' })).status, 200);
    assert.equal((await post('/v1/admin/viewers/reactivate', admin, { staffId: 'staff-a', reason: 'Example restoration' })).status, 409);
    assert.equal((await fetch(base + '/v1/history/record-a', { headers: authHeader })).status, 404);
    assert.equal((await fetch(ownUrl, { headers: authHeader })).status, 404);
    const validAfter = writer.prepare('SELECT token_valid_after FROM memberships WHERE subject = ?').get('example-viewer').token_valid_after;
    const deadline = Date.now() + 3000;
    while (Math.floor(Date.now() / 1000) < validAfter && Date.now() < deadline) await new Promise((done) => setTimeout(done, 30));
    assert.ok(Math.floor(Date.now() / 1000) >= validAfter);
    const freshViewer = await signed('example-viewer', 'timetable:access');
    assert.equal((await fetch(base + '/v1/history/record-a', { headers: { authorization: `Bearer ${freshViewer}` } })).status, 200);
    assert.equal(writer.prepare('SELECT COUNT(*) AS n FROM membership_reactivation_events WHERE actor_staff_id = ?').get('admin-a').n, 1);
    writer.prepare('UPDATE memberships SET active = 0 WHERE subject = ?').run('example-viewer');
    writer.prepare('INSERT INTO memberships (issuer,subject,business_id,staff_id,role,active) VALUES (?,?,?,?,?,0)')
      .run(issuer, 'example-secondary', 'shop-a', 'staff-a', 'VIEWER');
    assert.deepEqual((await (await fetch(`${staffUrl}&cursor=admin-a`, { headers: adminHeaders })).json()).staff,
      [{ id: 'staff-a', role: null, status: 'needs_review' }]);
    assert.equal((await post('/v1/admin/viewers/reactivate', admin, { staffId: 'staff-a', reason: 'Example restoration' })).status, 409);
    assert.equal(writer.prepare('SELECT COUNT(*) AS count FROM authenticated_audit_events').get().count, 3);
    assert.equal(writer.prepare('SELECT COUNT(*) AS count FROM authenticated_audit_events WHERE actor_staff_id = ?').get('admin-a').count, 3);
    assert.equal(writer.prepare('SELECT COUNT(*) AS count FROM history_close_events WHERE actor_staff_id = ?').get('admin-a').count, 1);
    writer.prepare('UPDATE memberships SET token_valid_after = ? WHERE subject = ?').run(validAfter + 100, 'example-admin');
    assert.equal((await fetch(staffUrl, { headers: adminHeaders })).status, 404);
    assert.equal((await fetch(adminList, { headers: adminHeaders })).status, 404);
    assert.equal((await fetch(adminShiftUrl, { headers: adminHeaders })).status, 404);
    assert.equal((await post('/v1/admin/viewers', admin, { staffId: 'staff-c', subject: 'example-third' })).status, 403);
    writer.prepare('UPDATE memberships SET token_valid_after = 0 WHERE subject = ?').run('example-admin');
    writer.prepare('UPDATE memberships SET role = ? WHERE subject = ?').run('VIEWER', 'example-admin');
    assert.equal((await fetch(adminList, { headers: adminHeaders })).status, 404);
    assert.equal((await post('/v1/admin/viewers', admin, { staffId: 'staff-b', subject: 'example-other' })).status, 403);
    assert.equal((await post('/v1/admin/history', admin, record)).status, 403);
    assert.equal(writer.prepare('SELECT COUNT(*) AS count FROM authenticated_audit_events').get().count, 3);
  } finally {
    if (service?.server.listening) await new Promise((close) => service.server.close(close));
    if (service?.db.isOpen) service.db.close();
    if (writer?.isOpen) writer.close();
    if (!resolve(temp).startsWith(resolve(prefix))) throw new Error('Unexpected temporary path');
    rmSync(temp, { recursive: true, force: true });
  }
});
